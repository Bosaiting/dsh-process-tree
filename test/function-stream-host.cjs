// Only a marked disposable loopback host. Never print the host URL/token.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { chromium } = require('playwright')
const redact = value => String(value).replace(/(token=)[^&\s'"]+/gi, '$1[redacted]')
const root = path.resolve(process.env.DSH_STREAM_TEST_DIR || '')
const hostLog = path.resolve(process.env.DSH_TEST_HOST_LOG || '')
if (!process.env.DSH_STREAM_TEST_DIR || !process.env.DSH_TEST_HOST_LOG || !fs.existsSync(path.join(root, '.dpt-disposable-test')) || !hostLog.startsWith(root + path.sep)) throw Error('requires a marked disposable test root and host log inside it')
const input = fs.readFileSync(hostLog, 'utf8').match(/http:\/\/127\.0\.0\.1:\d+\/\?token=\S+/)?.[0]
if (!input || new URL(input).hostname !== '127.0.0.1') throw Error('no isolated loopback host URL')
const waitPhase = async n => {
  fs.writeFileSync(path.join(root, `request-${n}`), 'go')
  for (let i = 0; i < 100; i++) {
    if (fs.existsSync(path.join(root, 'stream-error'))) throw Error(fs.readFileSync(path.join(root, 'stream-error'), 'utf8'))
    if (fs.existsSync(path.join(root, `completed-${n}`))) return
    await new Promise(resolve => setTimeout(resolve, 50))
  }
  throw Error(`fixture phase ${n} timed out`)
}
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.DSH_CHROMIUM_EXECUTABLE ? { executablePath: process.env.DSH_CHROMIUM_EXECUTABLE } : {}) })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage(), errors = []
  page.on('pageerror', error => errors.push(redact(error)))
  const checks=[]
  try {
    await page.goto(input, { waitUntil: 'networkidle' })
    const welcome=page.getByRole('button',{name:/^(继续|Continue)$/}), close=page.getByRole('button',{name:/^(关闭|Close)$/})
    if(await welcome.isVisible()){ await welcome.click(); await close.waitFor({state:'visible'}) }
    if(await close.isVisible())await close.click()
    const fixture=page.getByRole('treeitem').filter({hasText:'Process Tree Streaming Fixture'}).first()
    await fixture.waitFor({state:'visible',timeout:10000}); await fixture.click()
    await page.getByText('Synthetic fixture ready.').waitFor({state:'visible'})
    await page.getByRole('button',{name:/^(账号菜单|Account menu)$/}).click()
    await page.getByRole('menuitem',{name:/设置|Settings/}).click()
    await page.getByText('过程树',{exact:true}).click()
    await page.getByRole('radiogroup',{name:'风格'}).getByRole('radio',{name:/代码块/}).click()
    await page.getByRole('button',{name:/^(关闭|Close)$/}).click()
    await waitPhase(0); await page.waitForTimeout(200); assert.equal(await page.locator('[data-step-process-content] > [data-chat-group-part="reasoning"]').count(),0); checks.push({name:'empty reasoning block produces no host row',pass:true})
    await waitPhase(1)
    const row=page.locator('[data-step-process-content] > [data-chat-group-part="reasoning"]').last()
    await row.waitFor({state:'attached',timeout:5000})
    const anchor=await row.getAttribute('data-chat-anchor-key'); assert.ok(anchor)
    assert.equal((await row.textContent()).trim(),'');assert.equal(await row.locator('[data-variant="think"]').count(),0)
    checks.push({name:'signature-only row remains empty and filtered',pass:true})
    await waitPhase(2)
    await row.locator('[data-variant="think"]').waitFor({state:'attached'})
    await page.waitForTimeout(500)
    const liveHeader=row.locator('[data-disclosure-row]')
    const shimmer=liveHeader.locator('[data-shimmer]')
    const content=shimmer.locator('[data-dpt-function-comment-label]')
    const overlay=shimmer.locator(':scope > [aria-hidden="true"][inert]')
    assert.equal(await content.count(),1)
    assert.match(await content.evaluate(e=>getComputedStyle(e,'::before').content),/^"# "/)
    assert.equal(await overlay.evaluate(e=>getComputedStyle(e).display),'none')
    assert.equal(await content.locator('[data-dpt-function-caption]').count(),1)
    assert.equal(await content.locator('[data-dpt-function-caption]').isVisible(),false)
    assert.match(await content.innerText(),/Synthetic streaming thought\./)
    const bounds=await content.evaluate(e=>{const a=e.getBoundingClientRect(),b=e.lastElementChild.getBoundingClientRect();return {aTop:a.top,aBottom:a.bottom,bTop:b.top,bBottom:b.bottom}})
    assert.ok(bounds.bTop>=bounds.aTop-1 && bounds.bBottom<=bounds.aBottom+1,JSON.stringify(bounds))
    assert.equal(await liveHeader.getAttribute('aria-expanded'),'false')
    await liveHeader.click(); assert.equal(await liveHeader.getAttribute('aria-expanded'),'true')
    await liveHeader.click(); assert.equal(await liveHeader.getAttribute('aria-expanded'),'false')
    await row.screenshot({path:path.join(root,'stream-fixed.png')})
    assert.equal(await row.getAttribute('data-chat-anchor-key'),anchor)
    checks.push({name:'streaming thought has aligned comment marker and one visible text layer; native folding works',pass:true})
    await waitPhase(3)
    await page.waitForTimeout(300)
    assert.equal(await overlay.evaluate(e=>getComputedStyle(e).display),'none')
    assert.match(await content.evaluate(e=>getComputedStyle(e,'::before').content),/^"# "/)
    assert.equal(await row.locator('[data-dpt-function-comment-label]').count(),1)
    assert.equal(await row.getAttribute('data-chat-anchor-key'),anchor)
    checks.push({name:'streaming update preserves a single comment label and hides the decorative copy',pass:true})
    const selectStyle=async name=>{
      await page.getByRole('button',{name:/^(账号菜单|Account menu)$/}).click()
      await page.getByRole('menuitem',{name:/设置|Settings/}).click()
      await page.getByText('过程树',{exact:true}).click()
      await page.getByRole('radiogroup',{name:'风格'}).getByRole('radio',{name}).click()
      await page.getByRole('button',{name:/^(关闭|Close)$/}).click()
      for(let i=0;i<8;i++)await page.evaluate(()=>new Promise(requestAnimationFrame))
    }
    await selectStyle(/安静线条/)
    assert.notEqual(await overlay.evaluate(e=>getComputedStyle(e).display),'none')
    assert.equal(await row.locator('[data-dpt-function-comment-label]').count(),0)
    await selectStyle(/代码块/)
    assert.equal(await overlay.evaluate(e=>getComputedStyle(e).display),'none')
    assert.equal(await row.locator('[data-dpt-function-comment-label]').count(),1)
    checks.push({name:'other styles retain native shimmer and switching back restores code comment',pass:true})
    await waitPhase(4)
    await row.locator('[data-variant="think"][data-state="ok"]').waitFor({state:'attached'}); assert.ok((await row.textContent()).includes('Synthetic streaming thought.'))
    await page.waitForFunction(key=>{const row=[...document.querySelectorAll('[data-chat-anchor-key]')].find(el=>el.dataset.chatAnchorKey===key);return row?.querySelectorAll('[data-dpt-function-comment-label]').length===1},anchor)
    assert.equal(await row.locator('[data-dpt-function-comment-label]').count(),1)
    checks.push({name:'stream settles as a durable reasoning comment',pass:true})
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(root,'function-stream-results.json'),JSON.stringify({scope:'rc.5 real Web host with directly dispatched synthetic stream frames; no model requests or native Desktop claim',checks,errors},null,2)+'\n')
    console.log(JSON.stringify({checks,errors}))
  } finally { await context.close(); await browser.close() }
})().catch(error=>{console.error(redact(error.stack)); process.exitCode=1})
