// Marked disposable loopback DSH host with synthetic Session/PTC records only.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { chromium } = require('playwright')
const language = process.env.DPT_LANGUAGE || 'java'
assert.ok(['java', 'go'].includes(language))
const root = process.env.DPT_HOST_TEST_ROOT
assert.ok(root && fs.existsSync(path.join(root, '.dpt-disposable-test')), 'marked disposable root required')
assert.ok(process.env.DSH_HOME?.startsWith(root + path.sep), 'isolated DSH_HOME required')
const input = fs.readFileSync(process.env.DSH_TEST_HOST_LOG, 'utf8').match(/http:\/\/127\.0\.0\.1:\d+\/\?token=\S+/)?.[0]
assert.ok(input && new URL(input).hostname === '127.0.0.1', 'loopback host required')
const frames = page => page.evaluate(async () => { for (let i = 0; i < 12; i++) await new Promise(requestAnimationFrame) })
;(async () => {
  const browser = await chromium.launch({ headless: true }), page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = []
  page.on('pageerror', error => errors.push(String(error)))
  try {
    await page.goto(input, { waitUntil: 'networkidle' })
    const welcome = page.getByRole('button', { name: /^(继续|Continue)$/ }), close = page.getByRole('button', { name: /^(关闭|Close)$/ })
    if (await welcome.isVisible()) { await welcome.click(); await close.waitFor({ state: 'visible' }) }
    if (await close.isVisible()) await close.click()
    const fixture = page.getByRole('treeitem').filter({ hasText: 'Java Fallback Fixture' }).first()
    if (!await fixture.isVisible()) await page.getByText(/^(未分组|Ungrouped)$/, { exact: true }).click()
    await fixture.click()
    const activity = page.locator('[data-process-activity]').first()
    if (!await activity.isVisible()) await page.getByRole('button', { name: /已完成，用时|Completed.*\d/ }).first().click()
    if (await activity.getAttribute('aria-expanded') !== 'true') await activity.click()
    await page.waitForSelector('[data-chat-call-id="fallback-parent"]')
    await page.getByRole('button', { name: /^(账号菜单|Account menu)$/ }).click()
    await page.getByRole('menuitem', { name: /设置|Settings/ }).click()
    await page.getByText('过程树', { exact: true }).click()
    await page.getByRole('radiogroup', { name: '风格' }).getByRole('radio', { name: /代码块/ }).click()
    await page.getByRole('combobox', { name: '代码形态' }).selectOption('function')
    await page.getByRole('combobox', { name: '展示语言' }).selectOption(language)
    await page.getByRole('dialog').getByRole('button', { name: /^(关闭|Close)$/ }).click(); await frames(page)
    const parent = page.locator('[data-chat-call-id="fallback-parent"]'), header = parent.locator('[data-disclosure-row]').first()
    const child = page.locator('[data-chat-call-id="fallback-child"]'), special = page.locator('[data-chat-call-id="fallback-special"]')
    assert.equal(await header.locator('.dpt-code-expression').count(), 0)
    assert.ok((await header.innerText()).includes('参数'))
    const nativeExpanded = await header.getAttribute('aria-expanded')
    await header.locator('.dpt-code-more').click()
    assert.deepEqual(JSON.parse(await parent.locator('.dpt-code-arguments').first().innerText()), { code: 'read("child.java")', options: { safe: true } })
    assert.equal(await header.getAttribute('aria-expanded'), nativeExpanded)
    assert.match(await child.locator('.dpt-code-expression').innerText(), /^read\(\s*"child.java"\s*\)/)
    await header.locator('.dpt-scope-toggle').click(); await frames(page)
    assert.equal(await child.isVisible(), false)
    assert.match(await header.locator('.dpt-scope-failures').innerText(), /1/)
    await page.locator('.dpt-failure-count').click(); await frames(page)
    await page.locator('.dpt-failure-item').filter({ hasText: 'Synthetic child failure' }).click(); await frames(page)
    assert.equal(await child.isVisible(), true)
    assert.equal(await special.locator('.dpt-code-expression').count(), 0)
    await special.locator('.dpt-code-more').click()
    assert.deepEqual(JSON.parse(await special.locator('.dpt-code-arguments').innerText()), { path: 'synthetic.txt' })
    assert.deepEqual(errors, [])
    console.log('PASS native summaries and raw parameters for complex and special calls, nested folding and failure navigation')
  } finally { await browser.close() }
})().catch(error => { console.error(String(error.stack).replace(/(token=)[^&\s'\"]+/gi, '$1[redacted]')); process.exitCode = 1 })
